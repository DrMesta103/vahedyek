export function parseStoredStringList(value: string | boolean | undefined) {
  if (typeof value !== 'string' || !value.trim()) return [] as string[];

  try {
    const parsed = JSON.parse(value) as unknown;
    return Array.isArray(parsed) ? parsed.filter((item): item is string => typeof item === 'string') : [];
  } catch {
    return value
      .split('||')
      .map((item) => item.trim())
      .filter(Boolean);
  }
}

export function stringifyStringList(values: string[]) {
  return JSON.stringify(Array.from(new Set(values)));
}

export function toggleStoredStringList(currentValue: string | boolean | undefined, item: string) {
  const current = parseStoredStringList(currentValue);
  return stringifyStringList(current.includes(item) ? current.filter((value) => value !== item) : [...current, item]);
}
