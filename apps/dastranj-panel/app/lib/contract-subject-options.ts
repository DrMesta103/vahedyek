export function parseSubjectResponsibilities(subject: { responsibility: string; responsibilities?: string[] }) {
  if (Array.isArray(subject.responsibilities) && subject.responsibilities.length > 0) {
    return subject.responsibilities.filter((item) => item.trim());
  }
  const legacy = subject.responsibility.trim();
  if (!legacy) return [];
  return legacy.split('، ').map((item) => item.trim()).filter(Boolean);
}

export function formatSubjectResponsibilities(values: string[]) {
  return values.join('، ');
}
